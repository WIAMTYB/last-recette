-- Scheduler run history: one row per end-of-day or manual execution batch.
-- Additive; safe to run while the application is up. Run once as the EPARGNE schema owner.
CREATE TABLE EPARGNE_SCHEDULER_RUN (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRIGGER_TYPE VARCHAR2(20 CHAR) NOT NULL,
    OUTCOME VARCHAR2(20 CHAR) NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    FINISHED_AT TIMESTAMP,
    DURATION_MS NUMBER,
    BATCH_SIZE NUMBER NOT NULL,
    PROCESSED_COUNT NUMBER DEFAULT 0 NOT NULL,
    SUCCESS_COUNT NUMBER DEFAULT 0 NOT NULL,
    INSUFFICIENT_FUNDS_COUNT NUMBER DEFAULT 0 NOT NULL,
    BELOW_THRESHOLD_COUNT NUMBER DEFAULT 0 NOT NULL,
    ORDER_REJECTED_COUNT NUMBER DEFAULT 0 NOT NULL,
    TECHNICAL_FAILURE_COUNT NUMBER DEFAULT 0 NOT NULL,
    RETRIES_SCHEDULED_COUNT NUMBER DEFAULT 0 NOT NULL,
    CYCLES_SKIPPED_COUNT NUMBER DEFAULT 0 NOT NULL,
    NON_BUSINESS_DAY_DEFERRED_COUNT NUMBER DEFAULT 0 NOT NULL,
    PROCESSED_REFERENCES VARCHAR2(4000 CHAR),
    CORRELATION_ID VARCHAR2(120 CHAR) NOT NULL,
    TRIGGERED_BY VARCHAR2(120 CHAR),
    ERROR_MESSAGE VARCHAR2(1000 CHAR),
    CONSTRAINT CK_SCHEDULER_RUN_TRIGGER CHECK (TRIGGER_TYPE IN ('scheduled', 'manual')),
    CONSTRAINT CK_SCHEDULER_RUN_OUTCOME CHECK (OUTCOME IN ('RUNNING', 'SUCCESS', 'FAILURE'))
);

CREATE INDEX IDX_SCHEDULER_RUN_STARTED ON EPARGNE_SCHEDULER_RUN (STARTED_AT DESC);
CREATE INDEX IDX_SCHEDULER_RUN_OUTCOME ON EPARGNE_SCHEDULER_RUN (OUTCOME, STARTED_AT DESC);
