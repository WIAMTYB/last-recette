-- Shared API token security schema
--
-- Used by both:
--   - api-titres-selfcare
--   - epargne-programmee
--
-- These two services run independently but read/write the same Oracle tables
-- for API key authentication (header X-Api-Key: {tokenId}.{secret}).
--
-- Run this script ONCE on the shared database. If api-titres was deployed first,
-- the tables may already exist and this script can be skipped.
--
-- Epargne OPCVM reads tokens via ApiTokenRepository against:
--   API_CLIENT_TOKEN
--   API_CLIENT_TOKEN_AUTHORIZATION

CREATE TABLE API_CLIENT_TOKEN (
  TOKEN_ID VARCHAR2(80) NOT NULL,
  CLIENT_CODE VARCHAR2(120) NOT NULL,
  SECRET_HASH VARCHAR2(120) NOT NULL,
  ACTIVE NUMBER(1,0) DEFAULT 1 NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(120) NOT NULL,
  EXPIRES_AT TIMESTAMP DEFAULT NULL,
  DESCRIPTION VARCHAR2(500),
  CONSTRAINT API_CLIENT_TOKEN_PK PRIMARY KEY (TOKEN_ID),
  CONSTRAINT API_CLIENT_TOKEN_ACTIVE_CK CHECK (ACTIVE IN (0, 1))
);

CREATE INDEX API_CLIENT_TOKEN_IX1 ON API_CLIENT_TOKEN (CLIENT_CODE);

CREATE TABLE API_CLIENT_TOKEN_AUTHORIZATION (
  AUTHORIZATION_ID NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL,
  TOKEN_ID VARCHAR2(80) NOT NULL,
  PATH_PATTERN VARCHAR2(500) NOT NULL,
  HTTP_METHOD VARCHAR2(16),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(120) NOT NULL,
  CONSTRAINT API_CLIENT_TOKEN_AUTH_PK PRIMARY KEY (AUTHORIZATION_ID),
  CONSTRAINT API_CLIENT_TOKEN_AUTH_FK1 FOREIGN KEY (TOKEN_ID)
    REFERENCES API_CLIENT_TOKEN (TOKEN_ID),
  CONSTRAINT API_CLIENT_TOKEN_AUTH_METHOD_CK CHECK (
    HTTP_METHOD IS NULL OR HTTP_METHOD IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'HEAD')
  )
);

CREATE INDEX API_CLIENT_TOKEN_AUTH_IX1 ON API_CLIENT_TOKEN_AUTHORIZATION (TOKEN_ID);

CREATE UNIQUE INDEX API_CLIENT_TOKEN_AUTH_UK1 ON API_CLIENT_TOKEN_AUTHORIZATION (
  TOKEN_ID,
  PATH_PATTERN,
  NVL(HTTP_METHOD, '*')
);
