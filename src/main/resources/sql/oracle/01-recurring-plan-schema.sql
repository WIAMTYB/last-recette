-- At most 18 digits after EP, matching REFERENCE VARCHAR2(20 CHAR).
CREATE SEQUENCE EPARGNE_PLAN_REFERENCE_SEQ
    START WITH 1 INCREMENT BY 1
    MAXVALUE 999999999999999999
    NOCYCLE CACHE 20 NOORDER;

CREATE TABLE EPARGNE_SUBSCRIPTION_PLAN (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OPT_LOCK_VERSION NUMBER DEFAULT 0 NOT NULL,
    REFERENCE VARCHAR2(20 CHAR) NOT NULL,
    CLIENT_SEC_ACCOUNT VARCHAR2(20 CHAR) NOT NULL,
    CLIENT_CASH_ACCOUNT VARCHAR2(30 CHAR) NOT NULL,
    ASSET_CODE VARCHAR2(20 CHAR) NOT NULL,
    BY_AMOUNT NUMBER(1, 0) NOT NULL,
    AMOUNT NUMBER(19, 2),
    QUANTITY NUMBER(19, 6),
    FREQUENCY VARCHAR2(20 CHAR) NOT NULL,
    PREFERRED_DAY_OF_MONTH NUMBER NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    CURRENT_NOMINAL_CYCLE_DATE DATE NOT NULL,
    CURRENT_CYCLE_DUE_DATE DATE NOT NULL,
    NEXT_EXECUTION_DATE DATE NOT NULL,
    RETRY_DEADLINE_DATE DATE NOT NULL,
    LAST_ATTEMPT_DATE DATE,
    LAST_EXECUTION_DATE DATE,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT UK_SUBSCRIPTION_PLAN_REFERENCE UNIQUE (REFERENCE),
    CONSTRAINT CK_PLAN_MODE CHECK (
        (BY_AMOUNT = 1 AND AMOUNT IS NOT NULL AND QUANTITY IS NULL)
        OR
        (BY_AMOUNT = 0 AND QUANTITY IS NOT NULL AND AMOUNT IS NULL)
    )
);

CREATE INDEX IDX_SUBSCRIPTION_PLAN_DUE
    ON EPARGNE_SUBSCRIPTION_PLAN (STATUS, NEXT_EXECUTION_DATE);

CREATE TABLE EPARGNE_PLAN_EXECUTION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLAN_ID NUMBER NOT NULL,
    EXECUTED_AT TIMESTAMP NOT NULL,
    CYCLE_DUE_DATE DATE NOT NULL,
    ATTEMPT_NUMBER NUMBER NOT NULL,
    RESULT_STATUS VARCHAR2(30 CHAR) NOT NULL,
    EXECUTION_KEY VARCHAR2(120 CHAR) NOT NULL,
    EXTERNAL_ORDER_REFERENCE VARCHAR2(120 CHAR),
    MESSAGE VARCHAR2(1000 CHAR),
    CONSTRAINT FK_PLAN_EXECUTION_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES EPARGNE_SUBSCRIPTION_PLAN (ID),
    CONSTRAINT UK_PLAN_EXECUTION_ATTEMPT UNIQUE (PLAN_ID, CYCLE_DUE_DATE, ATTEMPT_NUMBER)
);

CREATE INDEX IDX_PLAN_EXECUTION_PLAN_DATE
    ON EPARGNE_PLAN_EXECUTION (PLAN_ID, EXECUTED_AT DESC);


CREATE TABLE EPARGNE_AUDIT_EVENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVENT_TIME TIMESTAMP NOT NULL,
    EVENT_TYPE VARCHAR2(80 CHAR) NOT NULL,
    ENTITY_TYPE VARCHAR2(60 CHAR) NOT NULL,
    ENTITY_REFERENCE VARCHAR2(120 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    ACTOR VARCHAR2(120 CHAR) NOT NULL,
    CORRELATION_ID VARCHAR2(120 CHAR) NOT NULL,
    PAYLOAD CLOB,
    ERROR_MESSAGE VARCHAR2(1000 CHAR)
);

CREATE INDEX IDX_AUDIT_EVENT_REFERENCE
    ON EPARGNE_AUDIT_EVENT (ENTITY_REFERENCE, EVENT_TIME DESC);
